//! Generate the token-based Harmony streaming fixture from canonical text.
//!
//! Run with `cargo run --bin gen_harmony_fixture`. It encodes the canonical
//! harmony tool-call text once, then slices the FULL token stream into chunks
//! (slicing, never re-encoding substrings, so concatenation == the full stream
//! and tokenization stays consistent across chunk boundaries). The result is a
//! committed, reproducible token fixture that drives the streaming parser test.

use dynamo_parsers_v2::{ExpectedCall, TokenChunk, TokenFixture, decode_harmony, encode_harmony};

fn main() -> anyhow::Result<()> {
    // TOOLCALLING.batch.1 (harmony family), one tool call.
    let canon = "<|channel|>commentary to=functions.get_weather <|constrain|>json<|message|>{\"location\":\"NYC\"}<|call|>";
    let tokens = encode_harmony(canon)?;

    let chunk_size = 4;
    let mut chunks = Vec::new();
    let mut i = 0;
    while i < tokens.len() {
        let end = (i + chunk_size).min(tokens.len());
        let slice = tokens[i..end].to_vec();
        let delta_text = decode_harmony(&slice).unwrap_or_default();
        chunks.push(TokenChunk {
            delta_text,
            delta_token_ids: slice,
            finish_reason: None,
        });
        i = end;
    }
    if let Some(last) = chunks.last_mut() {
        last.finish_reason = Some("tool_calls".to_string());
    }

    let fixture = TokenFixture {
        family: "harmony".to_string(),
        model_label: "gpt-oss".to_string(),
        description: "Single tool call, token-based stream (streaming POC). Derived from TOOLCALLING.batch.1; delta_token_ids are real gpt-oss tokens.".to_string(),
        chunks,
        expected_calls: vec![ExpectedCall {
            name: "get_weather".to_string(),
            arguments: serde_json::json!({"location": "NYC"}),
        }],
    };

    let yaml = serde_yaml::to_string(&fixture)?;
    let dir = concat!(env!("CARGO_MANIFEST_DIR"), "/fixtures");
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/fixtures/harmony.stream.tokens.1.yaml"
    );
    std::fs::create_dir_all(dir)?;
    let header = "# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n\
                  # SPDX-License-Identifier: Apache-2.0\n\
                  # Generated by `cargo run --bin gen_harmony_fixture`. Token-based Harmony streaming fixture.\n";
    std::fs::write(path, format!("{header}{yaml}"))?;
    println!("wrote {path} ({} chunks)", fixture_chunk_count(path)?);
    Ok(())
}

fn fixture_chunk_count(path: &str) -> anyhow::Result<usize> {
    let yaml = std::fs::read_to_string(path)?;
    let f: TokenFixture = serde_yaml::from_str(&yaml)?;
    Ok(f.chunks.len())
}
